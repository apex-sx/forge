  public final String defaultContextType;

  MIMEType(final String extension, final String... contextTypes) {
    this.extension = extension;
    this.contextTypes = contextTypes;
    this.defaultContextType = contextTypes[0];
  }

  /**
   * 解析出默认ContextType字符串
   *
   * @param filename 文件名
   * @return 返回ContextType字符串
   */
  public static String parseDefaultContextType(final String filename) {
    return MIMEType.parseMIMEType(filename).defaultContextType;
  }

  /**
   * 通过关键字解析出ContextType字符串
   *
   * @param filename 文件名
   * @param keyword  关键字
   * @return 返回ContextType字符串
   */
  public static String parseKeywordContextType(final String filename, final String keyword) {
    if (UtilsOfJudge.isInvalid(keyword)) {
      return MIMEType.parseDefaultContextType(filename);
    }
    final MIMEType mimeType = MIMEType.parseMIMEType(filename);
    if (mimeType.equals(MIMEType.UNKNOWN)) {
      return mimeType.defaultContextType;
    }
    final Object[] results = Arrays.stream(mimeType.contextTypes).filter(e -> e.contains(keyword))
        .toArray();
    if (results.length == 0) {
      MIMEType.LOGGER.info(
          "Don't found Content Type by keyword of" + keyword
              + ",and it will used default Context Type");
      return mimeType.defaultContextType;
    }
    if (results.length != 1) {
      MIMEType.LOGGER.info(
          "Found multiple Content Type by keyword of" + keyword
              + ",and it will used first Context Type");
    }
    return (String) results[0];
  }

  /**
   * 解析MIMEType
   *
   * @param filename 文件名或后缀
   * @return {@code MIMEType}
   */
  public static MIMEType parseMIMEType(final String filename) {
    final int len = filename.length();
    String handle;
    if (len > MIMEType.MAX_EXTENSION_LENGTH) {
      handle = filename.substring(len - MIMEType.MAX_EXTENSION_LENGTH);
    } else {
      handle = filename;
    }
    handle = handle.toLowerCase();
    final int last = handle.lastIndexOf(UtilsOfConstant.DOT);
    if (last != -1) {
      final String token = handle.substring(last + 1);
      final Optional<MIMEType> mimeType = Arrays.stream(MIMEType.values())
          .filter(e -> e.extension.equals(token))
          .findFirst();
      if (mimeType.isPresent()) {
        return mimeType.get();
      }
    }
    return MIMEType.UNKNOWN;
  }
