  @Override
  public Percentage parse(String num) {
    final Percentage[] percentages = Percentage.values();
    for (final Percentage percentage : percentages) {
      if (num.length() < 4) {
        int len = 5 - num.length();
        while (len-- != 0) {
          num += "0";
        }
      }
      if (percentage.num.equals(num)) {
        return percentage;
      }
    }
    throw new RuntimeException("No corresponding ratio found!");
  }

  @Override
  public BigDecimal scale() {
    return new BigDecimal(this.num);
  }
