package com.github.potatoxf.generals.utils.security.digest.signature;

import java.math.BigInteger;
import java.security.GeneralSecurityException;
import java.security.InvalidKeyException;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.interfaces.ECKey;
import java.util.Arrays;

/**
 * @author potatoxf
 */
class SignatureEllipticCurve extends SignatureMain {
    private static final String DER_ENCODING_SYS_PROPERTY_NAME =
            "com.github.potatoxf.generals.utils.security.digest.signature.SignatureEllipticCurve";

    SignatureEllipticCurve(CryptoSignatureEllipticCurve cryptoSignature, PrivateKey privateKey) throws GeneralSecurityException {
        super(cryptoSignature, privateKey);
        if (!(privateKey instanceof ECKey)) {
            throw new InvalidKeyException("Elliptic Curve signatures require an ECKey. The provided key of type " +
                    privateKey.getClass().getName() + " is not a " + ECKey.class.getName() + " instance.");
        }
    }

    SignatureEllipticCurve(CryptoSignatureEllipticCurve cryptoSignature, PublicKey publicKey) throws GeneralSecurityException {
        super(cryptoSignature, publicKey);
        if (!(publicKey instanceof ECKey)) {
            throw new InvalidKeyException("Elliptic Curve signatures require an ECKey. The provided key of type " +
                    publicKey.getClass().getName() + " is not a " + ECKey.class.getName() + " instance.");
        }
        ECKey ecKey = (ECKey) publicKey; // can cast here because of the Assert.isTrue assertion above
        BigInteger order = ecKey.getParams().getOrder();
        int keyFieldByteLength = (order.bitLength() + 7) / Byte.SIZE; //for ES512 (can be 65 or 66, this ensures 66)
        int concatByteLength = keyFieldByteLength * 2;
        if (concatByteLength != cryptoSignature.requiredByteLength) {
            String msg = "EllipticCurve key has a field size of " + keyFieldByteLength +
                    " bytes (" + (keyFieldByteLength * Byte.SIZE) + " bits)" +
                    ", but " + cryptoSignature.value() + " requires a field size of " +
                    cryptoSignature.fieldByteLength + " bytes (" + (cryptoSignature.fieldByteLength * Byte.SIZE) + " bits)" +
                    " per [RFC 7518, Section 3.4 (validation)]" +
                    "(https://datatracker.ietf.org/doc/html/rfc7518#section-3.4).";
            throw new InvalidKeyException(msg);
        }
    }

    @Override
    byte[] handleSignature(byte[] signature) {
        // mandated per https://datatracker.ietf.org/doc/html/rfc7518#section-3.4 :
        String value = cryptoSignature.value();
        CryptoSignatureEllipticCurve eccs = (CryptoSignatureEllipticCurve) cryptoSignature;
        byte[] derSignature;
        if (eccs.requiredByteLength != signature.length) {
            /*
             * If the expected size is not valid for JOSE, fall back to ASN.1 DER signature IFF the application
             * is configured to do so.  This fallback is for backwards compatibility ONLY (to support tokens
             * generated by early versions of jjwt) and backwards compatibility will be removed in a future
             * version of this library.  This fallback is only enabled if the system property is set to 'true' due to
             * the risk of CVE-2022-21449 attacks on early JVM versions 15, 17 and 18.
             */
            // TODO: remove for 1.0 (DER-encoding support is not in the JWT RFCs)
            if (signature[0] == 0x30 && "true".equalsIgnoreCase(System.getProperty(DER_ENCODING_SYS_PROPERTY_NAME))) {
                derSignature = signature;
            } else {
                String msg = "Provided signature is " + signature.length + " bytes (" + (signature.length * Byte.SIZE) + " bits)" +
                        " but " + eccs.value() + " signatures must be exactly " +
                        eccs.requiredByteLength + " bytes (" + (eccs.requiredByteLength * Byte.SIZE) + " bits)" +
                        " per [RFC 7518, Section 3.4 (validation)](https://datatracker.ietf.org/doc/html/rfc7518#section-3.4).";
                throw new RuntimeException(msg);
            }
        } else {
            //guard for JVM security bug CVE-2022-21449:
            ECKey ecKey = (ECKey) publicKey; // we can cast here because of the assertions made in the constructor
            BigInteger order = ecKey.getParams().getOrder();
            BigInteger r = new BigInteger(1, Arrays.copyOfRange(signature, 0, eccs.fieldByteLength));
            BigInteger s = new BigInteger(1, Arrays.copyOfRange(signature, eccs.fieldByteLength, signature.length));
            if (r.signum() < 1 || s.signum() < 1 || r.compareTo(order) >= 0 || s.compareTo(order) >= 0) {
                return null;
            }
            // Convert from concat to DER encoding since
            // 1) SHAXXXWithECDSAInP1363Format algorithms are only available on >= JDK 9 and
            // 2) the SignatureAlgorithm enum JCA alg names are all SHAXXXwithECDSA (which expects DER formatting)
            derSignature = CryptoSignatureEllipticCurve.transcodeConcatToDER(signature);
        }
        return derSignature;
    }
}
